func TestShouldUseInlineTable(t *testing.T) {
	t.Run("uses inline for small simple map", func(t *testing.T) {
		m := map[string]interface{}{
			"strategy": "basic",
			"user":     "admin",
		}
		assert.True(t, shouldUseInlineTable(m))
	})

	t.Run("does not use inline for large map", func(t *testing.T) {
		m := map[string]interface{}{
			"a": "1",
			"b": "2",
			"c": "3",
			"d": "4",
		}
		assert.False(t, shouldUseInlineTable(m))
	})

	t.Run("does not use inline for nested map", func(t *testing.T) {
		m := map[string]interface{}{
			"nested": map[string]interface{}{
				"key": "value",
			},
		}
		assert.False(t, shouldUseInlineTable(m))
	})

	t.Run("does not use inline for map with array", func(t *testing.T) {
		m := map[string]interface{}{
			"items": []interface{}{"a", "b"},
		}
		assert.False(t, shouldUseInlineTable(m))
	})
}

func TestFormatMultilineString(t *testing.T) {
	t.Run("formats multi-line string with triple quotes", func(t *testing.T) {
		input := "line1\nline2\nline3"
		result := formatMultilineString(input)
		assert.True(t, strings.HasPrefix(result, "'''\n"))
		assert.True(t, strings.HasSuffix(result, "\n'''"))
		assert.Contains(t, result, "line1")
		assert.Contains(t, result, "line2")
		assert.Contains(t, result, "line3")
	})
}
